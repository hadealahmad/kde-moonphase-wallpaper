var cachedMonthStarts = null;

/* Cumulative start (in Modified Julian Day numbers) of every tabulated month. */
function monthStarts() {
    if (cachedMonthStarts !== null) {
        return cachedMonthStarts;
    }

    var starts = [UMM_AL_QURA_FIRST_MJDN];
    var sum = UMM_AL_QURA_FIRST_MJDN;
    for (var i = 0; i < UMM_AL_QURA_MONTH_LENGTHS.length; ++i) {
        sum += UMM_AL_QURA_MONTH_LENGTHS[i];
        starts.push(sum);
    }
    cachedMonthStarts = starts;
    return starts;
}

/* Gregorian calendar date -> Julian Day number (Meeus, chapter 7). */
function gregorianToJdn(year, month, day) {
    var a = Math.floor((14 - month) / 12);
    var y = year + 4800 - a;
    var m = month + 12 * a - 3;
    return day + Math.floor((153 * m + 2) / 5) + 365 * y
           + Math.floor(y / 4) - Math.floor(y / 100) + Math.floor(y / 400)
           - 32045;
}

function fromUmmAlQura(mjdn, starts) {
    var lo = 0;
    var hi = starts.length - 1;
    while (lo + 1 < hi) {
        var mid = (lo + hi) >> 1;
        if (starts[mid] <= mjdn) {
            lo = mid;
        } else {
            hi = mid;
        }
    }

    var year = UMM_AL_QURA_FIRST_YEAR + Math.floor(lo / 12);
    return {
        year: year,
        month: (lo % 12) + 1,
        day: mjdn - starts[lo] + 1
    };
}

/* Tabular Islamic calendar (Kuwaiti algorithm), used outside the table. */
function fromTabular(jdn) {
    var l = jdn - 1948440 + 10632;
    var n = Math.floor((l - 1) / 10631);
    l = l - 10631 * n + 354;

    var j = Math.floor((10985 - l) / 5316) * Math.floor((50 * l) / 17719)
            + Math.floor(l / 5670) * Math.floor((43 * l) / 15238);
    l = l - Math.floor((30 - j) / 15) * Math.floor((17719 * j) / 50)
        - Math.floor(j / 16) * Math.floor((15238 * j) / 43) + 29;

    var month = Math.floor((24 * l) / 709);
    return {
        year: 30 * n + j - 30,
        month: month,
        day: l - Math.floor((709 * month) / 24)
    };
}

/*
 * Convert a JavaScript Date (its local calendar day) to the Hijri date.
 * Returned names are Arabic while the numerals stay Western (1..30, 1356..1500).
 */
function getHijriDate(date) {
    var d = date || new Date();
    var jdn = gregorianToJdn(d.getFullYear(), d.getMonth() + 1, d.getDate());
    var mjdn = jdn - 2400000;
    var starts = monthStarts();

    var h;
    if (mjdn >= starts[0] && mjdn < starts[starts.length - 1]) {
        h = fromUmmAlQura(mjdn, starts);
        h.source = "umm-al-qura";
    } else {
        h = fromTabular(jdn);
        h.source = "tabular";
    }

    h.weekday = d.getDay();
    h.monthName = HIJRI_MONTH_NAMES[h.month - 1];
    h.weekdayName = HIJRI_WEEKDAY_NAMES[h.weekday];
    return h;
}
